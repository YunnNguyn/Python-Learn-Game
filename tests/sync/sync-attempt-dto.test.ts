/**
 * Returns a NEW, mutable summary on every call. Never share one object between
 * records: zod keeps graderSummary by reference, so a shared fixture gets frozen
 * by deepFreeze() in one test and then breaks any later test that mutates it.
 */
function goodSummary() {
  return {
    executionStatus: RUNTIME_EXECUTION_STATUS.SUCCESS,
    gradingAvailable: true,
    gradingPassed: true,
    failedCategories: [] as string[],
  };
}

function makeRecord(overrides: Record<string, unknown> = {}): AttemptRecord {
  return AttemptRecordSchema.parse({
    id: "attempt.sync.1",
    activityId: "activity.test",
    missionTemplateId: "template.test",
    missionTemplateVersion: 2,
    seed: "play:activity.test:v2:variant:3",
    difficulty: Difficulty.EASY,
    conceptIds: ["concept.a", "concept.b"],
    learningStage: LearningStage.GUIDED,
    startedAt: "2026-10-03T11:59:00.000Z",
    submittedAt: "2026-10-03T12:00:00.000Z",
    passed: true,
    submissionIndex: 2,
    runCountBeforeSubmit: 3,
    hintsUsed: [HintLevel.H1, HintLevel.H2],
    runtimeErrorCount: 1,
    graderSummary: goodSummary(),
    ...overrides,
  });
}

function deepFreeze<T>(value: T): T {
  if (value !== null && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

/** Generates a record with the production Submit path (MissionAttemptSession). */
async function submitWithRealSession(grading: {
  passed: boolean;
  checks: unknown[];
}): Promise<AttemptRecord> {
  const activity = {
    id: "activity.test",
    type: LearningActivityType.CODE_MISSION,
    title: "Test",
    conceptIds: ["concept.test"],
    stage: LearningStage.GUIDED,
    missionTemplateId: "template.test",
  } as unknown as LearningActivity;
  const template = {
    id: "template.test",
    version: 1,
    conceptIds: ["concept.test"],
    allowedStages: [LearningStage.GUIDED],
    generator: { id: "generator.test" },
    grader: { id: "core.declarative", config: { checks: [{ type: "NO_EXCEPTION" }] } },
    runtime: { id: "runtime.test" },
  } as unknown as MissionTemplate;
  const instance = {
    id: "instance.test",
    templateId: template.id,
    templateVersion: 1,
    seed: "seed",
    difficulty: Difficulty.EASY,
    conceptIds: template.conceptIds,
    learner: { objective: "Do it" },
  } as MissionInstance;
  const runtime = {
    initialize: async () => ({ ok: true } as const),
    prepareMission: async () => ({ ok: true } as const),
    run: async () => ({ status: "SUCCESS", stdout: "", stderr: "" } as const),
    submit: async () =>
      ({ status: "SUCCESS", stdout: "", stderr: "", serialized: { variables: {} } }) as const,
    dispose() {},
  } satisfies RuntimeManager;
  const graders = {
    getGrader: () => ({ grade: () => grading }),
  } as unknown as GraderRegistry;
  const engine = new MissionEngine(runtime, graders);
  await engine.loadMission(template, instance);
  const session = new MissionAttemptSession(activity, template, instance, engine, {
    now: () => new Date("2026-10-03T10:00:00.000Z"),
  });
  return (await session.submit("answer = 42")).attemptRecord;
}

function toWireAndBack(record: AttemptRecord) {
  const dto = toSyncAttemptDtoV1(record);
  if (!dto.ok) throw new Error(`expected a DTO, got ${dto.error.code}`);
  return fromSyncAttemptDtoV1(JSON.parse(JSON.stringify(dto.value)));
}

describe("SyncAttemptDtoV1 round trip", () => {
  it("round-trips a record generated by the real Submit path, through JSON", async () => {
    const record = await submitWithRealSession({ passed: true, checks: [] });
    expect(record.graderSummary).toEqual(goodSummary());

    const back = toWireAndBack(record);
    expect(back).toEqual({ ok: true, value: record });
    if (back.ok) expect(back.value).toStrictEqual(record);
  });

  it("round-trips a failed real Submit including failedCategories", async () => {
    const record = await submitWithRealSession({
      passed: false,
      checks: [
        { type: "SHAPE", passed: false, category: GraderFailureCategory.SHAPE_ERROR },
        { type: "VALUE", passed: false, category: GraderFailureCategory.VALUE_ERROR },
        { type: "NO_EXCEPTION", passed: true },
      ],
    });
    expect(record.passed).toBe(false);
    expect(record.graderSummary?.failedCategories).toEqual([
      GraderFailureCategory.SHAPE_ERROR,
      GraderFailureCategory.VALUE_ERROR,
    ]);

    const back = toWireAndBack(record);
    expect(back.ok && back.value).toStrictEqual(record);
  });

  it("round-trips a record without the optional fields and invents nothing", () => {
    const record = AttemptRecordSchema.parse({
      id: "attempt.minimal",
      activityId: "activity.test",
      missionTemplateId: "template.test",
      missionTemplateVersion: 1,
      seed: "seed",
      difficulty: Difficulty.EASY,
      conceptIds: [],
      learningStage: LearningStage.GUIDED,
      submittedAt: "2026-10-03T12:00:00.000Z",
      passed: false,
      submissionIndex: 1,
      runCountBeforeSubmit: 0,
      hintsUsed: [],
      runtimeErrorCount: 0,
    });

    const dto = toSyncAttemptDtoV1(record);
    expect(dto.ok).toBe(true);
    const wire = JSON.parse(JSON.stringify(dto.ok ? dto.value : null));
    expect(wire.attempt).not.toHaveProperty("startedAt");
    expect(wire.attempt).not.toHaveProperty("graderSummary");

    const back = fromSyncAttemptDtoV1(wire);
    expect(back.ok && back.value).toStrictEqual(record);
    if (back.ok) {
      expect(back.value).not.toHaveProperty("startedAt");
      expect(back.value).not.toHaveProperty("graderSummary");
    }
  });

  it("preserves every persisted field value through JSON", () => {
    const record = makeRecord({
      graderSummary: {
        executionStatus: RUNTIME_EXECUTION_STATUS.TIMEOUT,
        gradingAvailable: false,
        gradingPassed: false,
        failedCategories: [GraderFailureCategory.RUNTIME_ERROR, GraderFailureCategory.RUNTIME_ERROR],
      },
    });
    const back = toWireAndBack(record);
    expect(back.ok).toBe(true);
    if (!back.ok) return;
    for (const key of Object.keys(record) as Array<keyof AttemptRecord>) {
      expect(back.value[key]).toStrictEqual(record[key]);
    }
    expect(Object.keys(back.value).sort()).toEqual(Object.keys(record).sort());
  });

  it.each(Object.values(RUNTIME_EXECUTION_STATUS))("accepts executionStatus %s", (status) => {
    const record = makeRecord({ graderSummary: { ...goodSummary(), executionStatus: status } });
    expect(toSyncAttemptDtoV1(record).ok).toBe(true);
  });

  it.each(Object.values(GraderFailureCategory))("accepts failed category %s", (category) => {
    const record = makeRecord({ graderSummary: { ...goodSummary(), failedCategories: [category] } });
    expect(toSyncAttemptDtoV1(record).ok).toBe(true);
  });

  it("accepts exactly the maximum number of failedCategories", () => {
    const record = makeRecord({
      graderSummary: {
        ...goodSummary(),
        failedCategories: Array(MAX_SYNC_FAILED_CATEGORIES).fill(GraderFailureCategory.VALUE_ERROR),
      },
    });
    expect(toSyncAttemptDtoV1(record).ok).toBe(true);
  });
});

describe("SyncAttemptDtoV1 rejection (never sanitizes)", () => {
  function expectUnsyncable(record: unknown, pathPrefix: string) {
    const result = toSyncAttemptDtoV1(record);
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error.code).toBe(SyncDtoErrorCode.UNSYNCABLE);
    expect(result.error.issues.some((issue) => issue.path.startsWith(pathPrefix))).toBe(true);
  }

  it.each(["code", "stdout", "sourceCode", "learnerOutput", "draft", "metadata"])(
    "rejects an unexpected graderSummary key %s instead of dropping it",
    (key) => {
      expectUnsyncable(makeRecord({ graderSummary: { ...goodSummary(), [key]: "x = 1" } }), "graderSummary");
    },
  );

  it.each([
    ["unknown executionStatus", { executionStatus: "EXPLODED" }],
    ["non-boolean gradingAvailable", { gradingAvailable: "yes" }],
    ["non-boolean gradingPassed", { gradingPassed: 1 }],
    ["unknown failure category", { failedCategories: ["NOT_A_CATEGORY"] }],
    ["failedCategories not an array", { failedCategories: "SHAPE_ERROR" }],
    ["free-text category", { failedCategories: ["print(open('secret'))"] }],
  ])("rejects %s", (_label, patch) => {
    expectUnsyncable(makeRecord({ graderSummary: { ...goodSummary(), ...patch } }), "graderSummary");
  });

  it.each(["executionStatus", "gradingAvailable", "gradingPassed", "failedCategories"])(
    "rejects a graderSummary missing %s (no defaults are fabricated)",
    (missing) => {
      const summary: Record<string, unknown> = { ...goodSummary() };
      delete summary[missing];
      expectUnsyncable(makeRecord({ graderSummary: summary }), "graderSummary");
    },
  );

  it("rejects an empty graderSummary object", () => {
    expectUnsyncable(makeRecord({ graderSummary: {} }), "graderSummary");
  });

  it("rejects more than the maximum failedCategories without mutating the input", () => {
    const record = deepFreeze(
      makeRecord({
        graderSummary: {
          ...goodSummary(),
          failedCategories: Array(MAX_SYNC_FAILED_CATEGORIES + 1).fill(GraderFailureCategory.VALUE_ERROR),
        },
      }),
    );
    const before = structuredClone(record);

    expectUnsyncable(record, "graderSummary.failedCategories");
    expect(record).toStrictEqual(before);
    expect(record.graderSummary?.failedCategories).toHaveLength(MAX_SYNC_FAILED_CATEGORIES + 1);
  });

  it("does not echo offending values in error issues", () => {
    const canary = "CANARY_LEARNER_CODE_9f3a";
    const result = toSyncAttemptDtoV1(
      makeRecord({ graderSummary: { ...goodSummary(), code: canary, executionStatus: canary } }),
    );
    expect(result.ok).toBe(false);
    expect(JSON.stringify(result)).not.toContain(canary);
  });

  it("rejects unknown AttemptRecord fields in both directions", () => {
    const withExtra = { ...makeRecord(), syncRevision: 7 };
    expectUnsyncable(withExtra, "(root)");

    const result = fromSyncAttemptDtoV1({ dtoVersion: 1, attempt: withExtra });
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.error.code).toBe(SyncDtoErrorCode.INVALID_ATTEMPT);
  });

  it.each([
    ["missing required field", () => {
      const { passed: _passed, ...rest } = makeRecord();
      return rest;
    }],
    ["wrong field type", () => ({ ...makeRecord(), submissionIndex: "1" })],
    ["non-record value", () => "not a record"],
    ["null", () => null],
  ])("treats an invalid base record as unsyncable: %s", (_label, build) => {
    const result = toSyncAttemptDtoV1(build());
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.error.code).toBe(SyncDtoErrorCode.UNSYNCABLE);
  });

  it("rejects unknown envelope fields instead of ignoring them", () => {
    const result = fromSyncAttemptDtoV1({ dtoVersion: 1, attempt: makeRecord(), accountId: "acct-1" });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe(SyncDtoErrorCode.INVALID_ENVELOPE);
      expect(JSON.stringify(result)).not.toContain("acct-1");
    }
  });

  it.each([
    ["null", null],
    ["array", []],
    ["string", "x"],
    ["number", 1],
    ["missing dtoVersion", { attempt: makeRecord() }],
    ["missing attempt", { dtoVersion: 1 }],
  ])("rejects a malformed envelope: %s", (_label, payload) => {
    const result = fromSyncAttemptDtoV1(payload);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.error.code).toBe(SyncDtoErrorCode.INVALID_ENVELOPE);
  });

  it.each([2, 0, 1.5, 99])("rejects unsupported dtoVersion %s and reports it", (version) => {
    const result = fromSyncAttemptDtoV1({ dtoVersion: version, attempt: makeRecord() });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe(SyncDtoErrorCode.UNSUPPORTED_VERSION);
      expect(result.error.receivedVersion).toBe(version);
    }
  });

  it("reports a future version even when the payload has fields this build does not know", () => {
    const result = fromSyncAttemptDtoV1({ dtoVersion: 2, attempt: { future: true }, extra: 1 });
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.error.code).toBe(SyncDtoErrorCode.UNSUPPORTED_VERSION);
  });

  it("does not report a receivedVersion for a non-numeric version", () => {
    const result = fromSyncAttemptDtoV1({ dtoVersion: "1", attempt: makeRecord() });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe(SyncDtoErrorCode.UNSUPPORTED_VERSION);
      expect(result.error).not.toHaveProperty("receivedVersion");
    }
  });
});

describe("SyncAttemptDtoV1 contents and immutability", () => {
  it("contains only the envelope, AttemptRecord fields and the four summary keys", () => {
    const dto = toSyncAttemptDtoV1(makeRecord());
    expect(dto.ok).toBe(true);
    if (!dto.ok) return;

    expect(Object.keys(dto.value).sort()).toEqual(["attempt", "dtoVersion"]);
    expect(dto.value.dtoVersion).toBe(SYNC_ATTEMPT_DTO_VERSION);
    const allowedFields = new Set(Object.keys(AttemptRecordSchema.shape));
    for (const key of Object.keys(dto.value.attempt)) expect(allowedFields.has(key)).toBe(true);
    expect(Object.keys(dto.value.attempt.graderSummary ?? {}).sort()).toEqual([
      "executionStatus",
      "failedCategories",
      "gradingAvailable",
      "gradingPassed",
    ]);
  });

  it("never mutates a deep-frozen input, on success or failure", () => {
    const good = deepFreeze(makeRecord());
    const bad = deepFreeze(makeRecord({ graderSummary: { ...goodSummary(), extra: 1 } }));
    const goodBefore = structuredClone(good);
    const badBefore = structuredClone(bad);

    expect(toSyncAttemptDtoV1(good).ok).toBe(true);
    expect(toSyncAttemptDtoV1(bad).ok).toBe(false);
    expect(good).toStrictEqual(goodBefore);
    expect(bad).toStrictEqual(badBefore);
  });

  it("returns a DTO that shares no references with the input", () => {
    // Own, mutable fixture: not frozen by any other test, not shared with other records.
    const record = makeRecord({ graderSummary: goodSummary() });
    const dto = toSyncAttemptDtoV1(record);
    expect(dto.ok).toBe(true);
    if (!dto.ok) return;

    expect(dto.value.attempt).not.toBe(record);
    expect(dto.value.attempt.graderSummary).not.toBe(record.graderSummary);
    expect(dto.value.attempt.conceptIds).not.toBe(record.conceptIds);
    (record.graderSummary as { gradingPassed: boolean }).gradingPassed = false;
    expect(dto.value.attempt.graderSummary).toEqual(goodSummary());
  });
});

describe.each([
  ["MemoryLearningPersistence", (_idb: ReturnType<typeof useIsolatedIndexedDb>) => new MemoryLearningPersistence()],
  [
    "IndexedDbLearningPersistence",
    (idb: ReturnType<typeof useIsolatedIndexedDb>) =>
      idb.track(new IndexedDbLearningPersistence(idb.createFactory())),
  ],
] as ReadonlyArray<readonly [string, (idb: ReturnType<typeof useIsolatedIndexedDb>) => LearningPersistence]>)(
  "SyncAttemptDtoV1 vs addAttemptIfAbsent full-record equality: %s",
  (_name, build) => {
    const idb = useIsolatedIndexedDb();

    it("returns exists for the remote copy of an unchanged stored record", async () => {
      const store = build(idb);
      const original = await submitWithRealSession({ passed: true, checks: [] });
      await store.addAttempt(original);

      const back = toWireAndBack(original);
      expect(back.ok).toBe(true);
      if (!back.ok) return;
      expect(await store.addAttemptIfAbsent(back.value)).toEqual({ status: "exists" });
      expect(await store.getAttempts()).toEqual([original]);
    });

    it("returns exists for a record without optional fields", async () => {
      const store = build(idb);
      const { startedAt: _s, graderSummary: _g, ...minimal } = makeRecord();
      const original = AttemptRecordSchema.parse(minimal);
      await store.addAttempt(original);

      const back = toWireAndBack(original);
      expect(back.ok && (await store.addAttemptIfAbsent(back.value))).toEqual({ status: "exists" });
    });

    it("keeps full-record conflict semantics: a different graderSummary is a conflict", async () => {
      const store = build(idb);
      const original = makeRecord();
      await store.addAttempt(original);

      const remote = toWireAndBack(
        makeRecord({ graderSummary: { ...goodSummary(), gradingPassed: false } }),
      );
      expect(remote.ok && (await store.addAttemptIfAbsent(remote.value))).toEqual({ status: "conflict" });
      expect(await store.getAttempts()).toEqual([original]);
    });

    it("a remote copy imported into an empty store is added and reads back identical", async () => {
      const store = build(idb);
      const original = makeRecord();
      const back = toWireAndBack(original);

      expect(back.ok && (await store.addAttemptIfAbsent(back.value))).toEqual({ status: "added" });
      const [stored] = await store.getAttempts();
      expect(stored).toStrictEqual(original);
    });
  },
);
